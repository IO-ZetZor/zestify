#!/usr/bin/env python3
"""Generate hyprlock config from the Zestify palette and run hyprlock."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".gif"}
VIDEO_EXTENSIONS = {".mp4", ".webm", ".mkv", ".mov"}

FALLBACK_COLOURS = {
    "background": "020305",
    "onBackground": "e6e4f0",
    "surface": "020305",
    "surfaceContainerHigh": "08090d",
    "primary": "bfc4ee",
    "onPrimary": "383e61",
    "error": "f97386",
}


def home() -> Path:
    return Path(os.environ.get("HOME", str(Path.home())))


def state_dir() -> Path:
    base = os.environ.get("XDG_STATE_HOME")
    return Path(base) if base else home() / ".local" / "state"


def cache_dir() -> Path:
    base = os.environ.get("XDG_CACHE_HOME")
    return (Path(base) if base else home() / ".cache") / "zestify"


def config_path() -> Path:
    base = os.environ.get("XDG_CONFIG_HOME")
    return (Path(base) if base else home() / ".config") / "zestify" / "config.json"


def read_config() -> dict:
    try:
        data = json.loads(config_path().read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def read_scheme() -> dict:
    path = state_dir() / "zestify" / "scheme.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(data, dict) and isinstance(data.get("colours"), dict):
            return data
    except (OSError, ValueError):
        pass
    return {"name": "zestify-fallback", "mode": "dark", "colours": dict(FALLBACK_COLOURS)}


def rgb(value: str) -> str:
    text = str(value or "").strip().lstrip("#")
    if len(text) == 8:
        text = text[:6]
    if len(text) != 6 or any(ch not in "0123456789abcdefABCDEF" for ch in text):
        text = "000000"
    return "rgb(%s)" % text.lower()


def palette(scheme: dict) -> dict:
    colours = scheme.get("colours") if isinstance(scheme.get("colours"), dict) else {}
    merged = dict(FALLBACK_COLOURS)
    for key, value in colours.items():
        if isinstance(value, str):
            merged[key] = value
    return merged


def wallpaper_state() -> Path:
    return state_dir() / "zestify" / "wallpaper"


def current_wallpaper() -> str:
    config = read_config()
    primary = str(config.get("monitor", {}).get("primary", "eDP-1"))
    state = wallpaper_state()
    for path in (state / "monitors" / (primary + ".txt"), state / "path.txt"):
        try:
            value = path.read_text(encoding="utf-8").strip()
        except OSError:
            continue
        if value:
            return value
    return ""


def lock_frame(source: str) -> str:
    path = Path(source).expanduser()
    suffix = path.suffix.lower()
    if suffix in IMAGE_EXTENSIONS and path.is_file():
        return str(path.resolve())
    if suffix not in VIDEO_EXTENSIONS or not path.is_file() or not shutil.which("ffmpeg"):
        return ""
    try:
        stamp = "%s:%s:%s" % (path.resolve(), path.stat().st_size, path.stat().st_mtime_ns)
    except OSError:
        return ""
    key = hashlib.sha256(stamp.encode("utf-8")).hexdigest()[:24]
    target = cache_dir() / "lock" / (key + ".jpg")
    if target.exists() and target.stat().st_size > 0:
        return str(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-ss", "1", "-i", str(path), "-frames:v", "1",
         "-vf", "scale=1920:-2", str(target)],
        capture_output=True,
        timeout=30,
    )
    if result.returncode == 0 and target.exists() and target.stat().st_size > 0:
        return str(target)
    return ""


def build_config(scheme: dict, background: str = "", font_family: str = "SF Pro") -> str:
    colours = palette(scheme)
    background = background or ""
    return """# Generated by zestify lock. Do not edit; it is regenerated on every lock.
background {{
    monitor =
    path = {background}
    color = {bg}
    blur_passes = 2
    brightness = 0.92
}}

input-field {{
    monitor =
    size = 260, 46
    outline_thickness = 2
    dots_size = 0.25
    dots_spacing = 0.2
    outer_color = {primary}
    inner_color = {surface}
    font_color = {foreground}
    fade_on_empty = false
    placeholder_text = Enter Password...
    position = 0, 0
    halign = center
    valign = center
}}

label {{
    monitor =
    text = $TIME
    color = {foreground}
    font_size = 64
    font_family = {font}
    position = 0, 180
    halign = center
    valign = center
}}
""".format(
        background=background,
        bg=rgb(colours["background"]),
        primary=rgb(colours["primary"]),
        surface=rgb(colours["surfaceContainerHigh"]),
        foreground=rgb(colours["onBackground"]),
        font=font_family,
    )


def output_path(value: str | None) -> Path:
    if value:
        return Path(value).expanduser()
    base = os.environ.get("XDG_CONFIG_HOME")
    return (Path(base) if base else home() / ".config") / "zestify" / "hyprlock.conf"


def wrote(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def qs_bin() -> str:
    return os.environ.get("QS_BIN") or shutil.which("qs") or "qs"


def ipc_call(method: str, value: str) -> None:
    try:
        subprocess.run(
            [qs_bin(), "ipc", "-c", "zestify", "call", "zestify", method, value],
            capture_output=True,
            timeout=3,
        )
    except (OSError, subprocess.TimeoutExpired):
        pass


def process_alive(pid: int) -> bool:
    try:
        with open("/proc/%d/stat" % pid, "r", encoding="utf-8") as handle:
            fields = handle.read().rsplit(") ", 1)
        if len(fields) != 2:
            return False
        return fields[1].split()[0] != "Z"
    except OSError:
        return False


def watcher_command(pid: int) -> list[str]:
    return [sys.executable, str(Path(__file__).resolve()), "--watch-pid", str(pid)]


def watch(pid: int) -> int:
    while process_alive(pid):
        time.sleep(0.5)
    ipc_call("lockState", "false")
    return 0


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(prog="zesti lock")
    parser.add_argument("--wait", action="store_true", help="wait for hyprlock to exit")
    parser.add_argument("--config-only", action="store_true", help="only write the config")
    parser.add_argument("--out", help="config output path")
    parser.add_argument("--watch-pid", type=int, help=argparse.SUPPRESS)
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    if args.watch_pid is not None:
        return watch(args.watch_pid)

    scheme = read_scheme()
    config = read_config()
    font = str(config.get("theme", {}).get("font", "SF Pro"))
    background = lock_frame(current_wallpaper())
    text = build_config(scheme, background, font)
    target = output_path(args.out)
    wrote(target, text)

    if args.config_only:
        print(json.dumps({"ok": True, "config": str(target)}))
        return 0

    binary = os.environ.get("HYPRLOCK_BIN") or shutil.which("hyprlock")
    if not binary:
        ipc_call("lockState", "false")
        print(json.dumps({"ok": False, "error": "hyprlock not found"}))
        return 1

    try:
        process = subprocess.Popen([binary, "--config", str(target)])
    except OSError as error:
        ipc_call("lockState", "false")
        print(json.dumps({"ok": False, "error": str(error)}))
        return 1

    time.sleep(1.0)
    if process.poll() is not None:
        ipc_call("lockState", "false")
        print(json.dumps({"ok": False, "error": "hyprlock exited immediately"}))
        return 1

    ipc_call("lockState", "true")
    if args.wait:
        code = watch(process.pid)
        process.wait()
        return code

    subprocess.Popen(
        watcher_command(process.pid),
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )
    print(json.dumps({"ok": True, "pid": process.pid, "config": str(target)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
